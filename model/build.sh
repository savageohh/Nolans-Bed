#!/usr/bin/env bash
# Regenerate everything: model, viewer, cut list, calcs (twin + full).
# Renders need node + playwright: node model/render.js
set -euo pipefail
cd "$(dirname "$0")/.."
python3 model/bed.py --full >/dev/null
python3 model/bed.py          >/dev/null   # twin last, so viewer/cut list are twin
{
  echo "# Structural checks"
  echo
  echo "_Generated by \`model/build.sh\`. ASD with NDS reference values for **SPF #2** (the weakest common"
  echo "species at the big-box store — Doug-fir or SYP #2 are stronger). The rated occupant load is"
  echo "**300 lb**; strength checks apply a **2x impact factor (600 lb)** for kids jumping and dropping onto"
  echo "the deck. \"Use\" is demand/capacity: under 100% passes._"
  echo
  cat build/calcs_twin.md
  echo
  cat build/calcs_full.md
  echo
  echo "## Assumptions worth knowing"
  echo
  echo "- Vertical loads go into the posts through **wood bearing** on the routed housing shoulders. The bolts and"
  echo "  inserts only hold the joint closed and resist racking; they are not counted for vertical capacity."
  echo "- A point load on the deck goes mostly to the nearest rib (60% at 12in spacing); the mattress and plywood"
  echo "  spread the rest. Plywood-to-rib composite action is ignored, so the ribs are conservative."
  echo "- Sway is calculated with the end-frame mortise-and-tenon joints at 50% of fully rigid. Glued M&T joints"
  echo "  usually do better than that."
  echo "- Insert withdrawal allowable (300 lb, 3/8-16 in softwood face grain) is a conservative assumption. Do the"
  echo "  pull test in DESIGN.md on a scrap of *your* lumber with *your* inserts before trusting it."
  echo "- This is a careful hobbyist analysis, not a stamped engineering design or a certification to ASTM F1427."
} > docs/CALCS.md
{
  echo "# Material cost estimate"
  echo
  echo "_Generated by \`model/build.sh\` from the cut list and hardware counts. Lumber and plywood are priced"
  echo "as **estimated Menards shelf prices (low–high), late 2026**. Check menards.com for your store and"
  echo "edit \`PRICES\` at the top of \`model/bed.py\`. Spares are the ~15% extra boards the cut list"
  echo "recommends. Tax is Minnesota: 6.875% state, and 9.025% combined in Minneapolis. Your rate depends"
  echo "on the store's city and county, so check the MN Dept. of Revenue rate guide. The Menards 11% rebate"
  echo "comes back as store credit, so it isn't subtracted here (it's worth roughly \$35–60)._"
  echo
  cat build/cost_twin.md
  echo
  cat build/cost_full.md
  echo
  echo "## Ways to spend less"
  echo
  echo "- Buy lumber during a Menards 11% rebate week, or in the lumber sales flyer."
  echo "- Use a zinc 50-pack of 3/8-16 inserts instead of E-Z Hex 25-packs. Do the pull test from DESIGN.md first."
  echo "- Buy the spare boards, then return the ones you don't use (keep the receipt). That's about \$50–80."
  echo "- Already applied: OSB deck, 1x8 pine end panels, a diagonal brace instead of a back panel,"
  echo "  one insert size, felt pads instead of glides, and finish only on visible parts. Glue and"
  echo "  sandpaper are assumed on hand."
  echo "- Buy bolts by the box instead of from the bin. Box pricing often runs half the per-piece bin price."
} > docs/COST.md
